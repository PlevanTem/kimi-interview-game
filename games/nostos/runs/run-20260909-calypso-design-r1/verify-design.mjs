import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const root = 'games/nostos/runs/run-20260909-calypso-design-r1';
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const hash = b => crypto.createHash('sha256').update(b).digest('hex');
const walk = d => fs.readdirSync(d, {withFileTypes:true}).flatMap(e => e.isDirectory() ? walk(path.join(d,e.name)) : [path.join(d,e.name)]);
const index = read('games/nostos/context/index.json');
const plan = read(`${root}/asset-plan.json`);
const input = read(`${root}/input-snapshot.json`);
const registry = read('games/nostos/context/asset-registry.json');
const run = read(`${root}/run.json`);
for (const p of [...Object.values(index.sources), ...index.readOrder, ...input.sources]) assert(fs.existsSync(p), `Missing context: ${p}`);
assert.equal(index.activeRunId, run.runId);
assert.equal(index.gateState.gate3, 'not_started');
assert.equal(run.humanVisualApproval, false);
assert.equal(plan.status, 'candidate_not_implemented');
assert.equal(new Set(plan.assets.map(a=>a.id)).size, plan.assets.length);
const known = new Set(registry.assets.map(a=>a.id));
for(const a of plan.assets) {
  assert(a.id.startsWith('game.nostos.'));
  assert(['existing','proposed_unallocated'].includes(a.registration));
  assert.equal(known.has(a.id), a.registration === 'existing', `ID status: ${a.id}`);
}
const scene = fs.readFileSync('games/nostos/src/game/scenes/calypso.ts','utf8');
for(const i of plan.interactions) assert(scene.includes(i.id), `Missing existing interaction: ${i.id}`);
assert.equal(new Set(plan.interactions.map(i=>i.id)).size,8);
assert.deepEqual(['clue','talk','memory','depart'].map(k=>plan.interactions.filter(i=>i.kind===k).length),[5,1,1,1]);
assert.equal(plan.interactions.find(i=>i.kind==='memory').seconds,66);
assert.equal(plan.interactions.find(i=>i.kind==='depart').requiresMemory,true);
assert.equal(plan.stumpGroups.reduce((n,g)=>n+g.count,0),20);
assert.equal(plan.stumpGroups.filter(g=>g.includesAxeStump).length,1);
assert.equal(plan.rills.branchCount,4);
assert.equal(new Set(plan.rills.directions).size,4);
assert.equal(hash(fs.readFileSync(input.reference.path)),input.reference.sha256);
const runtime = walk(input.runtimeBefore.root).sort().map(f=>[f.replaceAll('\\','/'),hash(fs.readFileSync(f))]);
assert.equal(runtime.length,input.runtimeBefore.files);
assert.equal(hash(JSON.stringify(runtime)),input.runtimeBefore.sha256,'Runtime changed during design-only revision');
const docPath='games/nostos/docs/CALYPSO_ENVIRONMENT_ASSET_PLAN.md';
const doc=fs.readFileSync(docPath,'utf8');
for(const m of doc.matchAll(/\]\(([^)]+)\)/g)) if(!/^https?:/.test(m[1])) assert(fs.existsSync(path.resolve(path.dirname(docPath),m[1])),`Broken document link: ${m[1]}`);
console.log(JSON.stringify({status:'PASS',scope:'design-contracts-only',assets:plan.assets.length,existingIds:plan.assets.filter(a=>a.registration==='existing').length,proposedIds:plan.assets.filter(a=>a.registration==='proposed_unallocated').length,interactions:8,stumps:20,rills:4,runtimeFilesUnchanged:runtime.length,runtimeSha256:input.runtimeBefore.sha256,notVerified:['terrain','visual quality','runtime integration','performance']},null,2));
